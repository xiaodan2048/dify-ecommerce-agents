def main(product: str, platform: str, note: str) -> dict:
    pid = (product or "").split(" ")[0].strip()
    if pid not in PRODUCTS:
        return {"status": "error", "message": f"未找到商品：{product}", "dossier": "", "product_name": "",
                "qual_info": "", "product_json": "{}", "rules_json": "{}"}
    p = PRODUCTS[pid]

    lines = [
        f"商品编号：{pid}",
        f"商品名称：{p['名称']}",
        f"品类：{p['品类']}",
        f"资质类型：{p['资质类型']}",
        f"批准文号：{p['批准文号']}",
        f"批准功效：{('、'.join(p['批准功效'])) if p['批准功效'] else '无（不能宣称任何保健功效）'}",
        f"价格：{p['价格']}",
        "",
        "【商品参数】",
    ]
    for i, t in enumerate(p["参数"], 1):
        lines.append(f"{pid}-参{i}：{t}")
    lines.append("")
    lines.append("【买家评价原话】")
    for i, t in enumerate(p["评价"], 1):
        lines.append(f"{pid}-评{i}：{t}")
    lines.append("")
    lines.append(f"【品牌调性】{BRAND['调性']}")
    lines.append(f"【品牌目标人群】{BRAND['人群']}")

    source = {}
    for i, t in enumerate(p["参数"], 1):
        source[f"{pid}-参{i}"] = t
    for i, t in enumerate(p["评价"], 1):
        source[f"{pid}-评{i}"] = t

    product_json = {
        "编号": pid,
        "名称": p["名称"],
        "资质类型": p["资质类型"],
        "批准功效": p["批准功效"],
        "依据": source,
        "平台": platform,
        "运营补充要求": note or "",
    }
    qual_info = "\n".join(lines[2:6])
    return {
        "status": "ok",
        "message": "",
        "dossier": "\n".join(lines),
        "product_name": p["名称"],
        "qual_info": qual_info,
        "product_json": json.dumps(product_json, ensure_ascii=False),
        "rules_json": json.dumps(RULES, ensure_ascii=False),
    }
