def _d(s):
    return datetime.strptime(s, "%Y-%m-%d").date()


def _s(d):
    return d.strftime("%Y-%m-%d")


def _md(d):
    return d.strftime("%m%d")


def _cn(d):
    return str(d.month) + "月" + str(d.day) + "日"


