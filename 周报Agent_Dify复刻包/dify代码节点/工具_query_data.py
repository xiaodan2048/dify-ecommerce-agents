def _raw(code, d):
    i = (d - DATA_START).days
    rows = DAILY.get(code) or []
    if i < 0 or i >= len(rows):
        return None
    return rows[i]


def _day(code, d):
    """把一行压缩数据还原成带字段名的字典。"""
    r = _raw(code, d)
    if r is None:
        return None
    v = r[0:5]
    n = SKU_N[code]
    units = r[5:5 + n]
    j = 5 + n
    pm, refund, spend, clicks, ad_gmv, st, hours, kol, live_gmv, reviews, bad, kw, dsr = r[j:j + 13]
    gmv_sku = [round(units[k] * SKUS[code][k][1] * pm, 1) for k in range(n)]
    gmv = round(sum(gmv_sku), 1)
    orders = sum(units)
    vis = sum(v)
    return {"date": d, "v": v, "visitors": vis, "orders": orders, "gmv": gmv, "units": units, "gmv_sku": gmv_sku,
            "refund": refund, "spend": spend, "clicks": clicks, "ad_gmv": ad_gmv, "ad_status": TXT[st],
            "live_hours": hours, "kol": TXT[kol], "live_gmv": live_gmv, "reviews": reviews, "bad": bad,
            "bad_kw": TXT[kw], "dsr": dsr}


def _pct(a, b):
    """a 相对 b 的变化，返回百分数（保留 1 位）。"""
    if not b:
        return None
    return round((a - b) / b * 100, 1)


def _sp(x):
    if x is None:
        return "—"
    return ("+" if x > 0 else ("−" if x < 0 else "")) + str(abs(x)) + "%"


def _money(x):
    return "{:,.0f}".format(x)


def _code(shop):
    s = SHOPS.get((shop or "").strip())
    return s["code"] if s else None


def _perm(operator_id, shop):
    p = PERM.get((operator_id or "").strip().upper())
    return bool(p) and (shop or "").strip() in p["shops"]


